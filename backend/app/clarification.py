"""按问题类型追问一次现实背景，不调用语言模型猜起卦信息。"""
import re
def followup_question(question: str) -> str:
    q = question.strip()
    if re.search(r"复合|分手|前任|挽回|和好",q):
        return "你们目前是断联、冷战，还是正在沟通中？双方是否有现实中的阻碍？"
    if re.search(r"感情|恋爱|婚姻|结婚|对象|喜欢|桃花|相亲|男友|女友",q):
        return "你们目前是什么关系、相处到哪个阶段，有没有已经发生的现实阻碍？"
    if re.search(r"找|丢|不见|失物|寻找",q) and re.search(r"东西|物品|猫|狗|钥匙|手机|发簪|包|宠物",q):
        return "最后一次确实见到它是在哪里、什么时候？你已经找过哪些地方？"
    if re.search(r"跳槽|工作|职业|事业|求职|面试|创业|升职|公司|老板",q):
        return "你现在的工作或机会处于什么阶段，眼前最大的现实阻碍是什么？"
    if re.search(r"考试|高考|学业|志愿|复读|录取|学校",q):
        return "目前的学习、成绩或录取情况是什么，眼前最需要解决的问题是什么？"
    if re.search(r"财运|投资|赚钱|生意|收入|买卖|借钱",q):
        return "你现在面对的是哪项具体收入或金钱决策？已有的事实和风险是什么？"
    if re.search(r"健康|生病|胸闷|症状|身体|失眠",q):
        return "你现在有哪些实际症状、持续多久、是否已接受医学评估？若有急症症状请先就医。"
    return "请补充这件事现在的真实处境、已经发生的情况，以及眼前最关键的阻碍是什么？"
